// Transpiles the restricted-Java region (between //@BEGIN-JS and //@END-JS) of the helper animation classes to JavaScript, so the studio runs
// the game's exact math.
// node anim/java2js.js  ->  anim/motion_core.js (HelperMotion) and anim/body_core.js (HelperBody)
const fs = require('fs');
const path = require('path');

const JAVA = path.resolve(__dirname, '..', '..', '..', 'blighted_helper', 'src', 'main', 'java', 'com', 'blighteddreams', 'helper', 'client');
const TARGETS = [
  { name: 'HelperMotion', src: path.join(JAVA, 'HelperMotion.java'), out: path.join(__dirname, 'motion_core.js') },
  { name: 'HelperBody', src: path.join(JAVA, 'HelperBody.java'), out: path.join(__dirname, 'body_core.js') },
];
const DEFAULTS = { int: '0', float: '0', boolean: 'false' };

function transpile(java) {
  const a = java.indexOf('//@BEGIN-JS'), b = java.indexOf('//@END-JS');
  if (a < 0 || b < 0) throw new Error('markers not found');
  let src = java.slice(a + '//@BEGIN-JS'.length, b);
  const names = new Set();
  const classes = [...src.matchAll(/static final class (\w+) \{/g)].map((m) => m[1]);
  const TYPES = `(?:float|int|boolean|${classes.join('|') || 'NONE'})(?:\\[\\])?`;

  // nested struct classes
  src = src.replace(/static final class (\w+) \{([\s\S]*?)\n    \}/g, (m, name, body) => {
    const fields = [];
    for (const line of body.split('\n')) {
      const f = line.match(/^\s*public\s+(\w+(?:\[\])?)\s+(\w+)\s*;/);
      if (f) fields.push([f[1], f[2]]);
    }
    names.add(name);
    return `class ${name} {\n    constructor() {\n${fields.map(([t, n]) => `      this.${n} = ${DEFAULTS[t] !== undefined ? DEFAULTS[t] : 'null'};`).join('\n')}\n    }\n  }`;
  });

  const out = [];
  let inArray = false;
  for (let line of src.split('\n')) {
    line = line.replace(/\b(\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)[fF]\b/g, '$1').replace(/\(float\)\s*/g, '').replace(/\(int\)\s*/g, '');
    if (inArray) {
      if (/\};\s*(\/\/.*)?$/.test(line)) { line = line.replace(/\};/, '];'); inArray = false; }
      out.push(line);
      continue;
    }
    // constant arrays (may span lines)
    let m = line.match(/^(\s*)static final (?:float|int)\[\] (\w+) = \{(.*)$/);
    if (m) {
      names.add(m[2]);
      let rest = m[3];
      if (/\};\s*(\/\/.*)?$/.test(rest)) rest = rest.replace(/\};/, '];'); else inArray = true;
      out.push(`${m[1]}const ${m[2]} = [${rest}`);
      continue;
    }
    // constants
    m = line.match(/^(\s*)static final (?:int|float|boolean) (.*);\s*(\/\/.*)?$/);
    if (m) { for (const n of m[2].split(',')) names.add(n.split('=')[0].trim()); out.push(`${m[1]}const ${m[2]};${m[3] ? ' ' + m[3] : ''}`); continue; }
    // methods
    m = line.match(/^(\s*)static\s+\w+(?:\[\])?\s+(\w+)\(([^)]*)\)\s*\{(.*)$/);
    if (m) {
      const params = m[3].split(',').map((p) => p.trim()).filter(Boolean).map((p) => p.split(/\s+/).pop());
      names.add(m[2]);
      out.push(`${m[1]}function ${m[2]}(${params.join(', ')}) {${m[4]}`);
      continue;
    }
    // locals and for-loop declarations
    line = line.replace(new RegExp(`^(\\s*)(?:final\\s+)?${TYPES}\\s+(\\w+)(\\s*[=;,])`), '$1let $2$3');
    line = line.replace(new RegExp(`\\bfor \\(${TYPES}\\s+(\\w+)`), 'for (let $1');
    // arrays
    line = line.replace(/new float\[([^\]]+)\]/g, 'new Float32Array($1)').replace(/new int\[([^\]]+)\]/g, 'new Int32Array($1)').replace(/new boolean\[([^\]]+)\]/g, 'new Array($1).fill(false)');
    line = line.replace(/new (\w+)\[([^\]]+)\]/g, 'new Array($2).fill(null)');
    out.push(line);
  }
  return { code: out.join('\n'), names: [...names] };
}

for (const t of TARGETS) {
  const { code, names } = transpile(fs.readFileSync(t.src, 'utf8'));
  const file = `// GENERATED by design/entitykit/anim/java2js.js from ${t.name}.java — do not edit.
const ${t.name} = (function () {
  const sin = Math.sin, cos = Math.cos, fexp = Math.exp, ifloor = Math.floor, sqrt = Math.sqrt, atan2 = Math.atan2, acos = Math.acos;
${code}
  return { ${names.join(', ')} };
})();
if (typeof module !== 'undefined') module.exports = ${t.name};
`;
  // a syntax check, so a construct the transpiler does not know fails here and not in the studio
  new Function(file.replace(/if \(typeof module[\s\S]*$/, ''));
  fs.writeFileSync(t.out, file);
  console.log('wrote', t.out, file.length, 'bytes,', names.length, 'symbols');
}
