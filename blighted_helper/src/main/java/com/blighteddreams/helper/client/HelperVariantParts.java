package com.blighteddreams.helper.client;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.neoforged.fml.loading.FMLPaths;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Extra model parts for the larger-texture helper variants (jester, infernal, holy), described in
 * {@code assets/blighted_helper/helper/variant_parts.json} (generated by design/entitykit/skin). A copy in
 * {@code config/blighted_helper-parts.json} overrides it, so parts can be tuned without rebuilding the mod
 * ({@code /helperavatar reloadparts}). The Gaia model itself never reads this file.
 */
public final class HelperVariantParts {
    private static final Logger LOGGER = LoggerFactory.getLogger("blighted_helper/variant_parts");
    private static final String RESOURCE = "/assets/blighted_helper/helper/variant_parts.json";
    private static final String OVERRIDE = "blighted_helper-parts.json";

    public static final class Cube {
        public float u, v, x, y, z, w, h, d, inflate;
        public boolean mirror;
    }

    public static final class Spec {
        public String name;
        public String parent;
        public final List<String> variants = new ArrayList<>();
        public float px, py, pz, rx, ry, rz;
        public final List<Cube> cubes = new ArrayList<>();
        /** copy the transform of this standard part every frame (so replacement wings flap like the originals) */
        public String follow;
        /** a follow part also copies the visibility of the part it follows */
        public boolean followVisible;
        /** sway amplitudes x,y,z (radians), speed, phase; {@code swayStep} adds phase per chain index */
        public float[] sway;
        /** uniform scale of a high-density subtree root (1/k); 1 when absent */
        public float scale = 1.0F;
        /** parts of one group share a spread channel (wing fans) or sit in a ring (skirts); ang is the ring angle / fan angle in radians */
        public String group;
        public float ang;
        public boolean hasAng;
        /** hidden at rest (juggling props): shown only when the motion layer raises their vis channel */
        public boolean hidden;
        public boolean hasPhys;
        /** spring parameters: period (ticks), damping ratio, gain, vertical coupling x / z, gravity counter-rotation */
        public float physP = 16.0F, physZ = 0.32F, physG = 1.0F, physVx, physVz, physGc;

        public boolean appliesTo(String variant) {
            return variants.contains(variant);
        }
    }

    public static final class Data {
        public final List<Spec> parts = new ArrayList<>();
        /** variant -> names of standard parts that are hidden for it */
        public final Map<String, List<String>> hide = new HashMap<>();
        /** variant -> standard part name -> {sx, sy, sz}: small per-variant body proportion changes */
        public final Map<String, Map<String, float[]>> tweak = new HashMap<>();
        public final java.util.Set<String> tweakNames = new java.util.HashSet<>();
        /** atlas size of the larger-texture model (older part files omit it) */
        public int texW = 256, texH = 128;
    }

    private static Data cached;

    private HelperVariantParts() {
    }

    public static synchronized Data get() {
        if (cached == null) cached = load();
        return cached;
    }

    public static synchronized void reload() {
        cached = null;
    }

    private static Data load() {
        Data data = new Data();
        try {
            Path override = FMLPaths.CONFIGDIR.get().resolve(OVERRIDE);
            Reader reader;
            if (Files.isRegularFile(override)) {
                reader = Files.newBufferedReader(override, StandardCharsets.UTF_8);
                LOGGER.info("Variant parts from {}", override);
            } else {
                InputStream in = HelperVariantParts.class.getResourceAsStream(RESOURCE);
                if (in == null) return data;
                reader = new InputStreamReader(in, StandardCharsets.UTF_8);
            }
            try (reader) {
                JsonObject root = new Gson().fromJson(reader, JsonObject.class);
                if (root.has("tex")) {
                    JsonArray tx = root.getAsJsonArray("tex");
                    data.texW = tx.get(0).getAsInt();
                    data.texH = tx.get(1).getAsInt();
                }
                JsonArray parts = root.getAsJsonArray("parts");
                if (parts != null) for (JsonElement pe : parts) data.parts.add(parse(pe.getAsJsonObject()));
                JsonObject hide = root.getAsJsonObject("hide");
                if (hide != null) {
                    for (Map.Entry<String, JsonElement> e : hide.entrySet()) {
                        List<String> names = new ArrayList<>();
                        for (JsonElement n : e.getValue().getAsJsonArray()) names.add(n.getAsString());
                        data.hide.put(e.getKey().toLowerCase(Locale.ROOT), names);
                    }
                }
                JsonObject tweak = root.getAsJsonObject("tweak");
                if (tweak != null) {
                    for (Map.Entry<String, JsonElement> e : tweak.entrySet()) {
                        Map<String, float[]> per = new HashMap<>();
                        for (Map.Entry<String, JsonElement> pe : e.getValue().getAsJsonObject().entrySet()) {
                            JsonArray a = pe.getValue().getAsJsonArray();
                            per.put(pe.getKey(), new float[]{a.get(0).getAsFloat(), a.get(1).getAsFloat(), a.get(2).getAsFloat()});
                            data.tweakNames.add(pe.getKey());
                        }
                        data.tweak.put(e.getKey().toLowerCase(Locale.ROOT), per);
                    }
                }
            }
        } catch (Exception e) {
            LOGGER.warn("Could not read variant parts: {}", e.toString());
        }
        return data;
    }

    private static float[] arr(JsonObject o, String key, int n) {
        float[] r = new float[n];
        if (o.has(key)) {
            JsonArray a = o.getAsJsonArray(key);
            for (int i = 0; i < n && i < a.size(); i++) r[i] = a.get(i).getAsFloat();
        }
        return r;
    }

    private static Spec parse(JsonObject o) {
        Spec s = new Spec();
        s.name = o.get("name").getAsString();
        s.parent = o.get("parent").getAsString();
        for (JsonElement v : o.getAsJsonArray("variants")) s.variants.add(v.getAsString().toLowerCase(Locale.ROOT));
        float[] p = arr(o, "pivot", 3), r = arr(o, "rot", 3);
        s.px = p[0]; s.py = p[1]; s.pz = p[2];
        s.rx = r[0]; s.ry = r[1]; s.rz = r[2];
        if (o.has("follow")) s.follow = o.get("follow").getAsString();
        if (o.has("followVisible")) s.followVisible = o.get("followVisible").getAsBoolean();
        if (o.has("sway")) s.sway = arr(o, "sway", 5);
        if (o.has("scale")) s.scale = arr(o, "scale", 3)[0];
        if (o.has("group")) s.group = o.get("group").getAsString();
        if (o.has("ang")) { s.ang = o.get("ang").getAsFloat(); s.hasAng = true; }
        if (o.has("hidden")) s.hidden = o.get("hidden").getAsBoolean();
        if (o.has("phys")) {
            JsonObject ph = o.getAsJsonObject("phys");
            s.hasPhys = true;
            if (ph.has("p")) s.physP = ph.get("p").getAsFloat();
            if (ph.has("z")) s.physZ = ph.get("z").getAsFloat();
            if (ph.has("g")) s.physG = ph.get("g").getAsFloat();
            if (ph.has("gc")) s.physGc = ph.get("gc").getAsFloat();
            if (ph.has("v")) { float[] v = arr(ph, "v", 2); s.physVx = v[0]; s.physVz = v[1]; }
        }
        for (JsonElement ce : o.getAsJsonArray("cubes")) {
            JsonObject c = ce.getAsJsonObject();
            Cube cube = new Cube();
            float[] uv = arr(c, "uv", 2), b = arr(c, "box", 6);
            cube.u = uv[0]; cube.v = uv[1];
            cube.x = b[0]; cube.y = b[1]; cube.z = b[2]; cube.w = b[3]; cube.h = b[4]; cube.d = b[5];
            cube.inflate = c.has("inflate") ? c.get("inflate").getAsFloat() : 0.0F;
            cube.mirror = c.has("mirror") && c.get("mirror").getAsBoolean();
            s.cubes.add(cube);
        }
        return s;
    }
}
