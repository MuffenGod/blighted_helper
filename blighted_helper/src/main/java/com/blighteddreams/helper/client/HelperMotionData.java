package com.blighteddreams.helper.client;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.neoforged.fml.loading.FMLPaths;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Animation data of the four Gaia-model helpers ({@code assets/blighted_helper/helper/motion.json}, generated by design/entitykit/anim).
 * A copy in {@code config/blighted_helper-motion.json} overrides it, so animations can be tuned without rebuilding the mod
 * ({@code /helperavatar reloadparts}). The raw JSON is turned into {@link HelperMotion} tracks per rig by {@link HelperMotionRig}.
 */
public final class HelperMotionData {
    private static final Logger LOGGER = LoggerFactory.getLogger("blighted_helper/motion");
    private static final String RESOURCE = "/assets/blighted_helper/helper/motion.json";
    private static final String OVERRIDE = "blighted_helper-motion.json";

    static final class RawTrack {
        String c;
        int mode;
        float[] keys = new float[0];
        int nkeys;
        float[] osc = new float[0];
        int nosc;
        float wIn = 0.15F, wOut = 0.15F, loop;
        int tb;
    }

    static final class RawClip {
        String name = "";
        float dur = 60.0F;
        final List<RawTrack> tracks = new ArrayList<>();
    }

    static final class RawVariant {
        RawClip idle, walk, run;
        final List<RawClip> flourish = new ArrayList<>();
    }

    private static Map<String, RawVariant> data;
    /** bumped on reload so cached rigs recompile */
    static volatile int generation = 0;

    private HelperMotionData() {
    }

    private static synchronized Map<String, RawVariant> get() {
        if (data == null) data = load();
        return data;
    }

    public static synchronized void reload() {
        data = null;
        generation++;
    }

    static RawVariant variant(String name) {
        return get().get(name.toLowerCase(Locale.ROOT));
    }

    public static boolean has(String variant) {
        return variant(variant) != null;
    }

    public static int flourishCount(String variant) {
        RawVariant v = variant(variant);
        return v == null ? 0 : v.flourish.size();
    }

    /** how long flourish idx plays, in ticks */
    public static int flourishTicks(String variant, int idx) {
        RawVariant v = variant(variant);
        if (v == null || idx < 0 || idx >= v.flourish.size()) return 60;
        return Math.round(v.flourish.get(idx).dur);
    }

    /** a particle / sound event placed on a flourish: name (ev.*) and normalised time */
    public record Event(String name, float t) {}

    private static final Map<String, List<List<Event>>> EVENTS = new HashMap<>();

    /** the ev.* pulses of flourish idx (keys whose value is 1), sorted by time */
    public static synchronized List<Event> events(String variant, int idx) {
        RawVariant v = variant(variant);
        if (v == null || idx < 0 || idx >= v.flourish.size()) return List.of();
        List<List<Event>> per = EVENTS.computeIfAbsent(variant.toLowerCase(Locale.ROOT) + "#" + generation, k -> new ArrayList<>());
        while (per.size() <= idx) per.add(null);
        List<Event> cached = per.get(idx);
        if (cached == null) {
            cached = new ArrayList<>();
            for (RawTrack t : v.flourish.get(idx).tracks) {
                if (!t.c.startsWith("ev.")) continue;
                for (int i = 0; i < t.nkeys; i++) if (t.keys[i * 3 + 1] >= 0.5F) cached.add(new Event(t.c, t.keys[i * 3]));
            }
            cached.sort((a, b) -> Float.compare(a.t(), b.t()));
            per.set(idx, cached);
        }
        return cached;
    }

    private static Map<String, RawVariant> load() {
        Map<String, RawVariant> out = new HashMap<>();
        try {
            Path override = FMLPaths.CONFIGDIR.get().resolve(OVERRIDE);
            Reader reader;
            if (Files.isRegularFile(override)) {
                reader = Files.newBufferedReader(override, StandardCharsets.UTF_8);
                LOGGER.info("Helper motion from {}", override);
            } else {
                InputStream in = HelperMotionData.class.getResourceAsStream(RESOURCE);
                if (in == null) return out;
                reader = new InputStreamReader(in, StandardCharsets.UTF_8);
            }
            try (reader) {
                JsonObject root = new Gson().fromJson(reader, JsonObject.class);
                JsonObject variants = root.getAsJsonObject("variants");
                if (variants == null) return out;
                for (Map.Entry<String, JsonElement> e : variants.entrySet()) {
                    JsonObject vo = e.getValue().getAsJsonObject();
                    RawVariant rv = new RawVariant();
                    rv.idle = clip(vo.get("idle"));
                    rv.walk = clip(vo.get("walk"));
                    rv.run = clip(vo.get("run"));
                    if (vo.has("flourish")) for (JsonElement f : vo.getAsJsonArray("flourish")) rv.flourish.add(clip(f));
                    out.put(e.getKey().toLowerCase(Locale.ROOT), rv);
                }
            }
        } catch (Exception ex) {
            LOGGER.warn("Could not read helper motion: {}", ex.toString());
        }
        return out;
    }

    private static RawClip clip(JsonElement el) {
        if (el == null || !el.isJsonObject()) return null;
        JsonObject o = el.getAsJsonObject();
        RawClip c = new RawClip();
        if (o.has("name")) c.name = o.get("name").getAsString();
        if (o.has("dur")) c.dur = o.get("dur").getAsFloat();
        if (o.has("tracks")) for (JsonElement te : o.getAsJsonArray("tracks")) c.tracks.add(track(te.getAsJsonObject()));
        return c;
    }

    private static RawTrack track(JsonObject o) {
        RawTrack t = new RawTrack();
        t.c = o.get("c").getAsString();
        t.mode = o.has("m") && "set".equals(o.get("m").getAsString()) ? 1 : 0;
        if (o.has("k")) {
            JsonArray k = o.getAsJsonArray("k");
            t.nkeys = k.size();
            t.keys = new float[t.nkeys * 3];
            for (int i = 0; i < t.nkeys; i++) {
                JsonArray kk = k.get(i).getAsJsonArray();
                t.keys[i * 3] = kk.get(0).getAsFloat();
                t.keys[i * 3 + 1] = kk.get(1).getAsFloat();
                t.keys[i * 3 + 2] = kk.size() > 2 ? kk.get(2).getAsFloat() : 1.0F;
            }
        }
        if (o.has("o")) {
            JsonArray os = o.getAsJsonArray("o");
            t.nosc = os.size();
            t.osc = new float[t.nosc * 4];
            for (int i = 0; i < t.nosc; i++) {
                JsonArray oo = os.get(i).getAsJsonArray();
                t.osc[i * 4] = oo.get(0).getAsFloat();
                t.osc[i * 4 + 1] = oo.get(1).getAsFloat();
                t.osc[i * 4 + 2] = oo.size() > 2 ? oo.get(2).getAsFloat() : 0.0F;
                t.osc[i * 4 + 3] = oo.size() > 3 ? oo.get(3).getAsFloat() : 1.0F;
            }
        }
        if (o.has("in")) t.wIn = o.get("in").getAsFloat();
        if (o.has("out")) t.wOut = o.get("out").getAsFloat();
        if (o.has("loop")) t.loop = o.get("loop").getAsFloat();
        if (o.has("tb")) t.tb = o.get("tb").getAsInt();
        return t;
    }
}
